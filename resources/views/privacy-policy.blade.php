    <h1>HopSurigao Privacy Policy</h1>
    <p>Last updated: November 7, 2026</p>

    <p>
        HopSurigao is a web and mobile platform for
        island-hopping tour reservations and management
        in Surigao del Norte.
        This policy explains how we handle personal
        information when users access the platform.
    </p>

    <h2>1. Information We Collect</h2>
    <p>
        Depending on the features used, we collect
        account information such as names, email
        addresses, phone numbers, reservation details,
        selected tour schedules, guest counts, and
        pickup information.
    </p>

    <h2>2. How We Use Information</h2>
    <p>
        We use this information to manage user accounts,
        process reservations, coordinate tours,
        confirm payments, provide booking updates,
        and support account recovery.
    </p>

    <h2>3. Payments</h2>
    <p>
        Online payments are processed through PayMongo.
        HopSurigao receives relevant payment status
        and transaction information to manage bookings.
        Payment information handled by PayMongo is also
        subject to PayMongo's privacy practices.
    </p>

    <h2>4. Gmail API and Password Recovery</h2>
    <p>
        HopSurigao uses Google's Gmail API to send
        password-recovery messages from an authorized
        system email account.
        The integration requests permission to send
        emails. It does not request permission to read
        users' Gmail inboxes.
    </p>
    <p>
        Registered users do not need to connect their
        personal Gmail accounts to receive password
        recovery messages.
        Google authorization credentials are used
        for operating the system email service and
        are not provided to tour customers.
    </p>

    <h2>5. Information Sharing</h2>
    <p>
        Information necessary for tour operations may
        be accessible to authorized administrators
        and tour operators.
        Service providers such as hosting and payment
        processors may process information needed
        to operate the platform.
    </p>

    <h2>6. Data Security</h2>
    <p>
        We use access controls and technical safeguards
        to help protect information. No online system
        can guarantee absolute security.
    </p>

    <h2>7. Data Retention</h2>
    <p>
        Information is retained as needed for account
        management, reservation operations, applicable
        recordkeeping obligations, and legitimate
        security purposes.
    </p>

    <h2>8. Your Privacy Rights</h2>
    <p>
        Users may contact us to ask about their
        personal data or request appropriate access,
        correction, or deletion, subject to applicable
        legal requirements.
    </p>

    <h2>9. Changes to This Policy</h2>
    <p>
        We may update this policy when system features
        or data practices change. The updated version
        will be posted on this page.
    </p>

